import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import solc from 'solc';
import { format } from 'prettier';
const source = await readFile(
  new URL('../contracts/SafeStateReader.sol', import.meta.url),
  'utf8',
);
assert.equal(solc.version().split('+')[0], '0.8.38');
const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: 'Solidity',
      sources: { 'SafeStateReader.sol': { content: source } },
      settings: {
        optimizer: { enabled: true, runs: 200 },
        evmVersion: 'paris',
        metadata: { bytecodeHash: 'none', appendCBOR: false },
        outputSelection: { '*': { '*': ['evm.deployedBytecode.object'] } },
      },
    }),
  ),
);
assert.equal(
  (output.errors ?? []).filter((e) => e.severity === 'error').length,
  0,
  JSON.stringify(output.errors ?? []),
);
const runtime =
  output.contracts['SafeStateReader.sol'].SafeStateReader.evm.deployedBytecode
    .object;
assert.ok(runtime.length > 0 && runtime.length < 24000);
const hash = createHash('sha256').update(source).digest('hex');
const generated = await format(
  `// Generated by scripts/safe-state-reader.mjs from contracts/SafeStateReader.sol.\n// solc 0.8.38; optimizer 200 runs; Paris EVM; metadata disabled.\n// Source SHA-256: ${hash}\nexport const safeStateReaderCode = '0x${runtime}';\n`,
  { parser: 'typescript', singleQuote: true, trailingComma: 'all' },
);
const destination = new URL(
  '../src/execution/safe-state-reader.generated.ts',
  import.meta.url,
);
if (process.argv.includes('--write')) await writeFile(destination, generated);
else
  assert.equal(
    await readFile(destination, 'utf8'),
    generated,
    'Regenerate Safe reader bytecode with npm run generate:read-helper',
  );
console.log(
  'Safe reader bytecode matches its source and pinned compiler settings',
);
